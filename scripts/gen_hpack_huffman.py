#!/usr/bin/env python3
"""Regenerate ``voxhound/app/_hpack_huffman.py`` from RFC 7541 Appendix B.

Kept in the repository because a 257-entry table pasted by hand is a
transcription bug waiting to happen, and because reviewers deserve a way to
verify the numbers against the source. Run::

    python scripts/gen_hpack_huffman.py [path-to-rfc7541.txt]

If no path is given the RFC is fetched from rfc-editor.org.
"""

from __future__ import annotations

import re
import sys
import urllib.request
from pathlib import Path

RFC_URL = "https://www.rfc-editor.org/rfc/rfc7541.txt"
ROW = re.compile(r"\(\s*(\d+)\)\s*\|([01|]+)\s+([0-9a-f]+)\s+\[\s*(\d+)\]")

TARGET = Path(__file__).resolve().parent.parent / "voxhound" / "app" / "_hpack_huffman.py"


def load_text(argv: list[str]) -> str:
    if len(argv) > 1:
        return Path(argv[1]).read_text(encoding="utf-8", errors="replace")
    with urllib.request.urlopen(RFC_URL, timeout=30) as response:  # noqa: S310 - fixed https URL
        return response.read().decode("utf-8", errors="replace")


def parse_rows(text: str) -> list[tuple[int, int, int]]:
    start = text.find("Appendix B.  Huffman Code")
    if start < 0:
        raise SystemExit("could not locate Appendix B in the RFC text")
    rows: list[tuple[int, int, int]] = []
    for line in text[start:].splitlines():
        match = ROW.search(line)
        if not match:
            continue
        symbol = int(match.group(1))
        code = int(match.group(3), 16)
        bits = int(match.group(4))
        rows.append((symbol, code, bits))
    if len(rows) != 257:
        raise SystemExit(f"expected 257 rows, parsed {len(rows)}")
    symbols = [row[0] for row in rows]
    if symbols != list(range(257)):
        missing = set(range(257)) - set(symbols)
        raise SystemExit(f"symbol coverage incomplete, missing {sorted(missing)[:8]}")
    return rows


def render(rows: list[tuple[int, int, int]]) -> str:
    lines = [
        '"""HPACK Huffman code table (RFC 7541, Appendix B).',
        "",
        "Generated by ``scripts/gen_hpack_huffman.py`` — do not edit by hand.",
        "Each entry is ``(code, bit_length)`` indexed by symbol; 256 is EOS.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "HUFFMAN_CODES: tuple[tuple[int, int], ...] = (",
    ]
    for symbol, code, bits in rows:
        comment = "EOS" if symbol == 256 else repr(chr(symbol))
        lines.append(f"    (0x{code:x}, {bits}),  # {symbol:3d} {comment}")
    lines.append(")")
    lines.append("")
    lines.append("#: Reverse lookup used by the decoder: ``(code, bits) -> symbol``.")
    lines.append("HUFFMAN_DECODE: dict[tuple[int, int], int] = {")
    lines.append("    (code, bits): symbol for symbol, (code, bits) in enumerate(HUFFMAN_CODES)")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    rows = parse_rows(load_text(argv))
    TARGET.write_text(render(rows), encoding="utf-8")
    sys.stdout.write(f"wrote {TARGET} ({len(rows)} symbols)\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
